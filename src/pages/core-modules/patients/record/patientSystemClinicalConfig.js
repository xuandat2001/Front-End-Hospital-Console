const DRAFT_RULE_GOVERNANCE = Object.freeze({
  version: "0.1.0-prototype",
  status: "draft",
  guideline:
    "Thresholds supplied in the healthcare specification; exact guideline versions were not supplied.",
  reviewedAt: null,
  reviewedBy: null,
  appliesTo: "Clinician-facing adult prototype unless a measurement states otherwise.",
  exclusions:
    "Pediatric, pregnancy, frailty, ethnicity, renal-disease, assay-specific, and individualized treatment-target exceptions remain incomplete.",
});

function draftRule(rule) {
  return {
    ...rule,
    governance: {
      ...DRAFT_RULE_GOVERNANCE,
      ...(rule.governance || {}),
    },
  };
}

function measurement({
  id,
  clinicalName,
  patientFriendlyName,
  unit,
  referenceRange,
  freshness,
  loincCodes = [],
  aliases = [],
  rule,
  trend,
  contextualModifiers = [],
  sourceTypes = [],
  clinicianObservation,
  patientMessage,
  clinicianOnly = false,
  validatedResultOnly = false,
}) {
  return {
    id,
    clinicalName,
    patientFriendlyName,
    unit,
    referenceRange,
    freshness,
    loincCodes,
    aliases,
    rule: draftRule(rule),
    trend,
    contextualModifiers,
    sourceTypes,
    clinicianObservation,
    patientMessage,
    clinicianOnly,
    validatedResultOnly,
  };
}

