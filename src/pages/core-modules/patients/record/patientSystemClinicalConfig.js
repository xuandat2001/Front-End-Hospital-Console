const VARIANT_ANATOMY_MESSAGES = Object.freeze({
  digestive: Object.freeze({
    male:
      "Partial 3D representation: stomach/intestine, liver, and gallbladder meshes are available in this model.",
    female:
      "Partial 3D representation: stomach/intestine and liver meshes are available; a gallbladder mesh is not present in this model.",
  }),
});

export function getAnatomyAvailability(systemId, modelVariant = "male") {
  const anatomy = getPatientSystemConfig(systemId).anatomy;
  const variantMessage =
    VARIANT_ANATOMY_MESSAGES[systemId]?.[modelVariant] || null;

  return variantMessage
    ? {
        ...anatomy,
        message: variantMessage,
      }
    : anatomy;
}

export function getMeasurementConfig(measurementId) {
  for (const systemId of PATIENT_SYSTEM_ORDER) {
    const system = PATIENT_SYSTEM_CLINICAL_CONFIG[systemId];
    const found = system.measurements.find((item) => item.id === measurementId);
    if (found) return { ...found, system: systemId };
  }
  return null;
}

export function getAllMeasurementConfigs() {
  return PATIENT_SYSTEM_ORDER.flatMap((systemId) =>
    PATIENT_SYSTEM_CLINICAL_CONFIG[systemId].measurements.map((item) => ({
      ...item,
      system: systemId,
    })),
  );
}
